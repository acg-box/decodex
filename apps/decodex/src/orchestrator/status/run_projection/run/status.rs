use crate::orchestrator::{
	AgentPrivateEvidenceRef, ChildAgentActivitySummary, CodexAccountActivitySummary,
	OperatorContinuationRecoveryStatus, OperatorLaneLifecycleMetrics, OperatorLoopStatus,
	OperatorRunAppServerState, OperatorRunLifecycleProjection, OperatorRunProtocolSummary,
	OperatorRunStatus, OperatorRunTiming, OperatorValidationEvidenceStatus, ProjectRunStatus,
	ProtocolActivitySummary, ServiceConfig, status_run_projection::runtime,
};

pub(crate) struct OperatorRunStatusParts<'a> {
	pub(crate) project: &'a ServiceConfig,
	pub(crate) project_display_name: &'a str,
	pub(crate) run: &'a ProjectRunStatus,
	pub(crate) lifecycle: OperatorRunLifecycleProjection,
	pub(crate) wait_reason: Option<String>,
	pub(crate) app_server_state: OperatorRunAppServerState,
	pub(crate) timing: OperatorRunTiming,
	pub(crate) protocol_summary: OperatorRunProtocolSummary,
	pub(crate) child_agent_activity: Option<ChildAgentActivitySummary>,
	pub(crate) protocol_activity: Option<ProtocolActivitySummary>,
	pub(crate) progress_diagnostic: Option<String>,
	pub(crate) account: Option<CodexAccountActivitySummary>,
	pub(crate) accounts: Vec<CodexAccountActivitySummary>,
	pub(crate) branch_name: Option<String>,
	pub(crate) worktree_path: Option<String>,
	pub(crate) issue_identifier: Option<String>,
	pub(crate) private_evidence: AgentPrivateEvidenceRef,
	pub(crate) continuation_recovery: Option<OperatorContinuationRecoveryStatus>,
	pub(crate) validation_evidence: Option<OperatorValidationEvidenceStatus>,
	pub(crate) active_goal_phase: Option<String>,
	pub(crate) public_progress_phase: Option<String>,
	pub(crate) loop_status: OperatorLoopStatus,
}

pub(crate) fn operator_run_status_from_parts(
	parts: OperatorRunStatusParts<'_>,
) -> OperatorRunStatus {
	let run_phase = parts.lifecycle.phase.clone();

	OperatorRunStatus {
		project_id: parts.project.service_id().to_owned(),
		project_display_name: parts.project_display_name.to_owned(),
		run_id: parts.run.run_id().to_owned(),
		issue_id: parts.run.issue_id().to_owned(),
		issue_identifier: parts.issue_identifier,
		title: None,
		author: None,
		issue_state: None,
		active_label_present: None,
		needs_attention_label_present: None,
		attempt_number: parts.run.attempt_number(),
		status: parts.lifecycle.status,
		attempt_status: parts.run.status().to_owned(),
		status_projection_reason: parts.lifecycle.status_projection_reason,
		ownership_state: String::new(),
		liveness_state: String::new(),
		policy_state: String::new(),
		terminalization_state: String::new(),
		lane_control_next_action: String::new(),
		lane_control_conditions: Vec::new(),
		phase: parts.lifecycle.phase,
		run_phase,
		wait_reason: parts.wait_reason,
		current_operation: parts.lifecycle.current_operation,
		active_goal_phase: parts.active_goal_phase,
		public_progress_phase: parts.public_progress_phase,
		control_capability: runtime::operator_run_control_capability(
			parts.run,
			&parts.app_server_state,
		),
		thread_id: parts.app_server_state.thread_id,
		turn_id: parts.app_server_state.turn_id,
		thread_status: parts.app_server_state.thread_status,
		thread_active_flags: parts.app_server_state.thread_active_flags,
		interactive_requested: parts.app_server_state.interactive_requested,
		continuation_pending: parts.app_server_state.continuation_pending,
		continuation_recovery: parts.continuation_recovery,
		validation_evidence: parts.validation_evidence,
		run_lease: parts.lifecycle.run_lease,
		queue_lease_state: runtime::operator_run_queue_lease_state(parts.lifecycle.run_lease),
		execution_liveness: parts.lifecycle.execution_liveness,
		has_fresh_execution: false,
		counts_as_running: false,
		needs_attention: false,
		updated_at: parts.run.updated_at().to_owned(),
		last_run_activity_at: runtime::format_optional_unix_timestamp(
			parts.timing.last_run_activity_unix_epoch,
		),
		last_protocol_activity_at: runtime::format_optional_unix_timestamp(
			parts.timing.last_protocol_activity_unix_epoch,
		),
		last_progress_at: runtime::format_optional_unix_timestamp(
			parts.timing.last_progress_unix_epoch,
		),
		idle_for_seconds: parts.timing.idle_for_seconds,
		protocol_idle_for_seconds: parts.timing.protocol_idle_for_seconds,
		suspected_stall: parts.lifecycle.suspected_stall,
		progress_diagnostic: parts.progress_diagnostic,
		last_event_type: parts.protocol_summary.last_event_type,
		last_event_at: parts.protocol_summary.last_event_at,
		event_count: parts.protocol_summary.event_count,
		private_evidence: parts.private_evidence,
		loop_status: Some(parts.loop_status),
		process_id: parts.timing.process_id,
		process_alive: parts.timing.process_alive,
		process_liveness_reason: parts.timing.process_liveness_reason,
		retry_kind: parts.lifecycle.retry_kind,
		next_retry_at: runtime::format_optional_unix_timestamp(
			parts.lifecycle.retry_ready_at_unix_epoch,
		),
		effective_model: parts.app_server_state.effective_model,
		effective_model_provider: parts.app_server_state.effective_model_provider,
		effective_cwd: parts.app_server_state.effective_cwd,
		effective_approval_policy: parts.app_server_state.effective_approval_policy,
		effective_approvals_reviewer: parts.app_server_state.effective_approvals_reviewer,
		effective_sandbox_mode: parts.app_server_state.effective_sandbox_mode,
		child_agent_activity: parts.child_agent_activity,
		protocol_activity: parts.protocol_activity,
		lifecycle_source: parts.run.recovery_source().to_owned(),
		lifecycle_evidence: parts.run.recovery_evidence().to_vec(),
		lifecycle_gaps: parts.run.recovery_gaps().to_vec(),
		lifecycle_metrics: OperatorLaneLifecycleMetrics::default(),
		account: parts.account,
		accounts: parts.accounts,
		branch_name: parts.branch_name,
		worktree_path: parts.worktree_path,
	}
}
